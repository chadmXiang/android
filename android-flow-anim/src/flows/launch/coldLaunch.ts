/**
 * 从 Launcher 冷启动应用 —— 四个维度共用的主脚本（示意时序 ms，非实测；类名 / 方法名 / 字段名对照 frameworks/base 源码）
 *
 * 泳道 = 实例（一个对象一条泳道），所以同一份数据可以：
 *   ① 按进程聚合 → 进程时序图（只看跨进程交互）
 *   ② 按进程过滤 → 进程内部的对象协作图（谁 new 了谁、字段怎么连起来）
 *   ③ 取生命周期对象 → 两个 Activity 的前台切换
 *   ④ 取 dump 事件 → dumpsys 前后变化
 *
 * 版本相关（源码核对）：
 *   - ATMS.startProcessAsync 把 ActivityManagerInternal::startProcess post 到 ATMS 的 mH（DisplayThread · android.display）
 *   - AMS.attachApplicationLocked：expedite_activity_launch_on_cold_start 打开时，立刻 mAtmInternal.attachApplication
 *     （下发 Launch + Resume）；关闭时要等应用 Application.onCreate 之后调 finishAttachApplication 才下发。本脚本按"打开"画。
 *   - enable_wait_for_finish_attach_application 默认 true：应用在 handleBindApplication 末尾 finishAttachApplication，
 *     AMS 再处理 Service / 广播（finishAttachApplicationInner）。
 */

