/**
 * 开机流程 —— 多维度主脚本（示意时序，非实测）
 *   init 部分对照 AOSP main 的 system/core/init 与 rootdir/init.rc（本机没有 system/core，取自 android.googlesource.com）；
 *   app_process / ZygoteInit / SystemServer / bootanimation / SurfaceFlinger / servicemanager 对照本机 base 与 native。
 *
 * 和本机源码一致、和常见描述不同的两点：
 *   - AMS.systemReady 里先 goingCallback.run()（PHASE 550 → 600），再 startHomeOnAllDisplays；
 *   - startSystemUi 在 systemReady(...) 返回之后才调（本机 SystemServer.startOtherServices），所以先 fork Launcher、再 fork SystemUI。
 */

const L = (id: string, cls: string, process: string, label?: string): LaneDef => ({...clsLane(id, cls, process, label), inst: id});
const I = (id: string, cls: string, process: string, group?: string, label?: string, fields?: Record<string, string>): InstanceDef => ({
  id,
  cls,
  process,
  group,
  label,
  fields,
});

const G = 'getprop（节选）';
const SL = 'service list（servicemanager）';
const PS = 'ps -A（关键进程）';
const SFL = 'SurfaceFlinger --list';

/** 复用旧脚本的服务网格 / boot phase 事件（时刻一致），泳道换成实例泳道 */
const LANE_MAP: Record<string, string> = {ss: 'ss', init: 'init2', sf: 'sf'};
const ported: FlowEvent[] = bootScript.events
  .filter((e) => e.type === 'service' || e.type === 'phase')
  .map((e) => (e.type === 'phase' && e.lane ? {...e, lane: LANE_MAP[e.lane] ?? 'ss'} : e));

/** init 主循环执行一个触发器 */
const trigger = (at: number, name: string, dur = 20, extra: FlowEvent[] = []): FlowEvent[] => [
  invoke(at, 'init2', 'am', `ExecuteOneCommand：on ${name}`, at + dur),
  span('am', at, at + dur, `on ${name}`, 'cpu'),
  set(at + 2, 'am', '当前触发器', name),
  ...extra,
];

/** init 启动一个 rc 里声明的 service：ActionManager → Service::Start → fork + exec */
const startSvc = (at: number, from: string, svc: string, lane: string, proc: string, label: string, name: string): FlowEvent[] => [
  invoke(at, from, svc, 'Service::Start', at + 15),
  span(svc, at, at + 15, 'fork + exec', 'cpu'),
  spawn(at + 10, svc, lane, proc, label),
  set(at + 12, svc, 'state', 'running'),
  prop(at + 12, 'init2', `init.svc.${name}`, 'running'),
  dump(at + 12, G, `init.svc.${name}`, 'running'),
];

