const byId = new Map(CLASSES.map((c): [string, ClassDef] => [c.id, c]));

export const hasClass = (id: string) => byId.has(id);

export const getClass = (id: string): ClassDef => {
  const c = byId.get(id);
  if (!c) throw new Error(`[catalog] 未知类: ${id}`);
  return c;
};

export const relationsOf = (id: string) => ({
  out: CLASS_RELATIONS.filter((r) => r.from === id),
  in: CLASS_RELATIONS.filter((r) => r.to === id),
});

const byName = new Map(CLASSES.map((c): [string, string] => [c.name, c.id]));

/**
 * 类的结构化成员：字符串 'mFoo: Bar' 拆成 name / type；
 * ref 先按关系 label 匹配（R(.., 'mFoo')），再按类型名匹配目录里的类。
 */
export const fieldsOf = (id: string): ClassField[] => {
  const c = getClass(id);
  const out = relationsOf(id).out;
  return (c.fields ?? []).map((raw) => {
    const i = raw.indexOf(':');
    const name = (i < 0 ? raw : raw.slice(0, i)).trim();
    const type = i < 0 ? undefined : raw.slice(i + 1).trim();
    const rel = out.find((r) => r.label === name || (!!type && r.label === type));
    const typeRef = type ? byName.get(type.replace(/[（(].*$/, '').trim()) : undefined;
    return {name, type, ref: rel?.to ?? typeRef, relation: rel?.kind};
  });
};
